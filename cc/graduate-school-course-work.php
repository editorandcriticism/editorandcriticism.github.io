<h1 class="title">Graduate Course Work</h1>
<p class="author"><i class="fa fa-pencil-square-o" aria-hidden="true"></i>
 Steve Hoenisch</p>
</header>
<p>Here’s a list of courses that I took during graduate school. Most of
the courses were in the sociology, philosophy, psychology, or
linguistics department at the Graduate Center, City University of New
York (CUNY). I also took graduate courses at Hartford University and the
University of Oregon (where I got my bachelor’s degree in
philosophy).</p>
<h2 id="the-graduate-center-city-university-of-new-york">The Graduate
Center, City University of New York</h2>
<ul>
<li>Literature as Social Knowledge. With Prof. <a
href="http://en.wikipedia.org/wiki/Stanley_Aronowitz">Stanley
Aronowitz</a>.</li>
<li>Introduction to Cultural Studies. With Prof. <a
href="http://soc.qc.cuny.edu/faculty/clough/">Patricia Clough</a>.</li>
<li>Culture and Democracy</li>
<li>Weber, Durkheim, Foucault</li>
<li>French Social Thought. With Prof. <a
href="http://maxweber.hunter.cuny.edu/socio/faculty/lazreg.html">Marnia
Lazreg.</a></li>
<li>Ethnomethodology</li>
<li>Grammar, Pragmatics, and Discourse Analysis. With Prof. <a
href="http://www.johndore.com/">John Dore</a>.</li>
<li>Language, Emotion, and Conflict. With Prof. <a
href="http://www.johndore.com/">John Dore</a>.</li>
<li>Wittgenstein and Freud</li>
<li>Wittgenstein: Philosophical Investigations</li>
<li>Introduction to Theoretical Linguistics</li>
<li>Linguistic Phonetics</li>
<li>Phonology</li>
<li>Syntax</li>
<li>Semantics</li>
<li>Pragmatics</li>
<li>Philosophy of Language. With Prof. <a
href="http://en.wikipedia.org/wiki/Jerrold_Katz">Jerrold Katz</a>.</li>
<li>Psycholinguistics</li>
<li>Computational Linguistics</li>
<li>Applied Linguistics</li>
<li>Sociolinguistics</li>
<li>Languages in Contact</li>
<li>Education Policy</li>
<li>Independent Research</li>
</ul>
