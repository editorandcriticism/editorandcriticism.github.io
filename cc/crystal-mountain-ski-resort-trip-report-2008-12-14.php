<h3
id="crystal-mountain-ski-area-opens-2008-season-with-a-powder-day">Crystal
Mountain Ski Area Opens 2008 Season with a Powder Day</h3>
<p>CASCADE MOUNTAINS, WASH., Dec. 14, 2008 -- A foot and a half of new
snow greeted me Saturday morning as I emerged from the Alpine Inn as the
season's first guest to get first tracks off Forest Queen on the first
run of Crystal Mountain's opening day.</p>
<p>Crystal Mountain kicked off the season by running only two lifts of
note: Chinook Express and the Queen. The few open runs on Forest Queen
soon got tracked out, so I trekked through the trees off Queens to the
top of Quick Silver for more first tracks, a tactic that proved
worthwhile to both avoid the crowds and ski fresh powder.</p>
<p>Until about 2 pm. That's when Crystal opened Raineer Express -- and,
to everyone's surprise, the Green Valley chair. More first tracks down
Green Valley bowl, Pro Course, and Lower Green Valley, all of which had
good coverage.</p>
<p><img alt="Blackcomb Mountain, BC." src="/photos/blackcomb-mountain-in-clouds.jpg" width="682" height="512" /></p>
<p>Mid-mountain at Blackcomb, winter, 2020.
<i class="fa fa-picture-o" aria-hidden="true"></i> by Steve
Hoenisch.</p>
<hr />
<p>By Saturday afternoon, the cold front that drifted over Raineer on
Friday morning had dropped nearly two feet of light snow on the upper
mountain, making the skiing feel more like early season at Snowbird than
in the Cascades. Still hit my share of rocks and bush, though.</p>
<p>On Saturday night, after doing my mat work, I decided I better dig
out my car before the 0 degree temperatures forecast for Sunday hit. On
Friday night, the plow driver had some fun building a wall of snow
around my car, which was one of only a few in the lot.</p>
<p>On Sunday morning, peaking out my window at the Alpine Inn, I gauged
there to be couple more inches of new. The temperature was about 8
degrees at the bottom of the mountain; one degree at the top with wind
that brought the wind chill to minus 22.</p>
<p>In the morning, I made a couple of quick warmup runs on Forest Queen
and Chinook Express, taking advantage of the empty, freshly groomed
slopes to make some Super-G turns at speed. Then I headed up Raineer
Express to hit Green Valley again, this time riding down Upper Ferk's
Run and then hiking up the cone to get some face shots through pristine
light and dry snow as I dropped into Lower Green Valley.</p>
<p>Of course, I asked the Pro Patrol if they were thinking about opening
High Campbell, but they said no, that it's all rock and gnarl on the top
because of the sparse snowpack and the strong winds.</p>
<p>But about 2 pm, I noticed that High Campbell was spinning and that
there were civilians on it.</p>
<p>At the top, freezing to death in the -22 wind chill, was a patroller.
"Only Powder Bowl is open," she said, "and the right side is rocky, and
the left side is chunky with avalanche debris." So hit the middle then?
"Yeah."</p>
<p>I dropped in and angled left, got in about four turns in virtually
untracked deep, light snow and then angled farther left, tip-toeing
through the crux between the islands of rock to avoid the obvious rocks
underfoot. Couldn't see anything and almost fell over from vertigo on a
ridge of snow. Past the rocks, I tentatively started turning and my skis
immediately crunched into what felt like rock. It was buried chunks of
avalanche debris, bowling ball size, hidden under the white-out smooth
surface. After two or three turns, the chunks let up and I opened it up
through untracked, thigh deep snow to the bottom of the bowl.</p>
<hr />
<p>Days No. 2 and 3 for the 2008-2009 ski season.</p>
<p>Trip Report by Steven Hoenisch. Published Dec. 15, 2008, in Seattle,
Wash.</p>
